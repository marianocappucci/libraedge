def test_la_app_es_tauri_2_con_su_lock():
    cargo = tomllib.loads(_texto(ESCRITORIO / "Cargo.toml"))
    assert cargo["dependencies"]["tauri"]["version"].startswith("2.")
    assert cargo["build-dependencies"]["tauri-build"]["version"].startswith("2.")
    assert cargo["features"]["default"] == ["custom-protocol"]
    lock = _texto(ESCRITORIO / "Cargo.lock")
    assert re.search(r'name = "tauri"\nversion = "2\.', lock)
    # Lo generado no va al repo.
    ignorados = set(_texto(ESCRITORIO / ".gitignore").split())
    assert {"target/", "gen/", "salida/", "permissions/autogenerated/"} <= ignorados


def test_el_producto_sale_de_la_definicion_del_instalador():
    build = _texto(ESCRITORIO / "build.rs")
    assert 'env::var("LIBRAEDGE_PRODUCTO")' in build and "cargo:rerun-if-env-changed=LIBRAEDGE_PRODUCTO" in build
    assert '.join("productos").join(format!("{producto}.json"))' in build
    for clave in ("nombre", "salud", "puerto"):
        assert f'"{clave}"' in build
    # Nombre, version, identificador e iconos por TAURI_CONFIG, para tauri_build y para generate_context!.
    assert 'env::set_var("TAURI_CONFIG"' in build and "cargo:rustc-env=TAURI_CONFIG=" in build
    assert 'format!("ar.com.librasuite.{producto}")' in build
    assert 'icono("png"), icono("ico")' in build


@pytest.mark.parametrize("producto", PRODUCTOS)
def test_cada_producto_tiene_sus_iconos_y_su_marca(producto):
    ico = INSTALADOR / "iconos" / f"{producto}.ico"
    png = INSTALADOR / "iconos" / f"{producto}.png"
    # El PNG (ventana de Linux, Tauri lo pide RGBA) es la entrada de 256 px del mismo .ico.
    assert png.read_bytes() == _armar_icono().png_de_ico(ico.read_bytes())
    ancho, alto, bits, color = re.match(rb"\x89PNG\r\n\x1a\n.{8}(.{4})(.{4})(.)(.)", png.read_bytes(), re.S).groups()
    assert (int.from_bytes(ancho, "big"), int.from_bytes(alto, "big"), bits, color) == (256, 256, b"\x08", b"\x06")
    assert (INSTALADOR / "marca" / f"{producto}.svg").is_file()


