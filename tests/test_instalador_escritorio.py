"""La version de escritorio de los productos (ADR-015): lo que se puede probar sin compilar ni instalar.

La app (``escritorio/``, Tauri 2) tiene sus pruebas de Rust (``cargo test``) y se compila, se instala y se prueba
de verdad en el workflow ``publicar-instalador.yml``: arranca y carga el producto local (``xvfb-run`` en Ubuntu, un
arranque cronometrado en Windows), el acceso directo apunta a ella, se vincula con el central de prueba y desinstalar
la saca. Aca: que las piezas coincidan entre si (nombres, rutas, el alfabeto del codigo, la accion de polkit, la
capacidad de las paginas) y la forma de lo que cambio en los instaladores.
"""

