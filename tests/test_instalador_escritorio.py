def _app_falsa(carpeta: Path, nombre: str) -> Path:
    carpeta.mkdir(parents=True, exist_ok=True)
    falsa = carpeta / nombre
    falsa.write_text(f'#!/bin/sh\necho "app $*" > "{carpeta}/abierto.txt"\n', encoding="utf-8")
    falsa.chmod(0o755)
    return falsa


@pytest.mark.parametrize("argumentos, esperado", [
    (["http://localhost:8100/"], "app"),
    ([], "app"),
    # El respaldo (la accion del .desktop y la app cuando no puede abrir su ventana): siempre el navegador.
    (["--navegador", "http://localhost:8100/"], "google-chrome --app=http://localhost:8100/"),
])
def test_abrir_producto_prefiere_la_app(tmp_path, argumentos, esperado):
    bash = shutil.which("bash")
    bin_ = tmp_path / "bin"
    _app_falsa(tmp_path / "escritorio", "libraedge-nodo-contalibra")
    chrome = _app_falsa(bin_, "google-chrome")
    chrome.write_text(f'#!/bin/sh\necho "google-chrome $*" > "{tmp_path}/escritorio/abierto.txt"\n')
    resultado = subprocess.run([bash, str(LINUX / "abrir_producto.sh"), *argumentos],
                               env={"PATH": str(bin_), "LIBRAEDGE_ESCRITORIO_DIR": str(tmp_path / "escritorio")},
                               capture_output=True, text=True, timeout=30)
    assert resultado.returncode == 0, resultado.stderr
    assert (tmp_path / "escritorio" / "abierto.txt").read_text(encoding="utf-8").strip() == esperado


