def test_el_iss_instala_la_app_y_la_abre_al_terminar():
    iss = _texto(INSTALADOR / "nodo.iss")
    assert ('Source: "paquete\\escritorio\\{#Producto}.exe"; DestDir: "{app}\\escritorio"; '
            'DestName: "{#NombreProducto}.exe"; Flags: ignoreversion skipifsourcedoesntexist') in iss
    correr = iss[iss.index("[Run]"):iss.index("[UninstallRun]")]
    assert 'Filename: "{app}\\escritorio\\{#NombreProducto}.exe"' in correr
    for bandera in ("postinstall", "nowait", "skipifsilent", "skipifdoesntexist", "runasoriginaluser"):
        assert bandera in correr
    desinstalar = iss[iss.index("[UninstallRun]"):iss.index("[UninstallDelete]")]
    assert '/F /IM ""{#NombreProducto}.exe""' in desinstalar
    # Una actualizacion cierra la app de cualquier sesion antes de reemplazar el .exe.
    prepara = iss[iss.index("function PrepareToInstall"):]
    assert "\\escritorio\\*'' } | Stop-Process -Force" in prepara[:prepara.index("\nend;")]
    # La firma queda preparada (sin certificado no se define Firmar).
    assert "#ifdef Firmar\nSignTool=firma\nSignedUninstaller=yes\n#endif" in iss


