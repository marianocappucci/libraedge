def test_los_comandos_de_la_app_y_quien_los_puede_llamar():
    main = _rust("main.rs")
    registrados = re.sub(r"\s", "", re.search(r"generate_handler!\[([^\]]+)\]", main).group(1)).split(",")
    manifiesto = re.search(r"\.commands\(&\[([^\]]+)\]\)", _texto(ESCRITORIO / "build.rs"), re.S).group(1)
    assert sorted(registrados) == sorted(re.findall(r'"(\w+)"', manifiesto))
    # Las pantallas propias (locales) pueden todo; el producto (remoto) solo la pantalla completa.
    paginas = json.loads(_texto(ESCRITORIO / "capabilities" / "paginas.json"))
    assert paginas["local"] is True and paginas["windows"] == ["principal"]
    assert sorted(paginas["permissions"]) == sorted(f"allow-{c.replace('_', '-')}" for c in registrados)
    assert "remote" not in paginas
    # Una capacidad remota por origen (la copia local, o la PC principal de un puesto, ADR-017), solo con F11.
    remota = main[main.index("fn permitir_f11("):]
    remota = remota[:remota.index("\n}\n")]
    assert 'CapabilityBuilder::new(format!("producto-{id}"))' in remota
    assert re.findall(r'\.permission\("([^"]+)"\)', remota) == ["allow-alternar-pantalla-completa"]
    assert 'format!("http://{host}:{}/*", origen.puerto)' in remota
    assert main.count("permitir_f11(") == 3  # la definicion, al arrancar y al elegir la PC principal


def test_el_codigo_y_la_direccion_se_validan_igual_que_en_el_instalador():
    vinculo = _rust("vinculo.rs")
    alfabeto = re.search(r'const ALFABETO: &str = "([^"]+)";', vinculo).group(1)
    assert alfabeto == ins._ALFABETO_DEL_CODIGO
    # La direccion, con los mismos caracteres que el .iss (DireccionValida).
    iss = _texto(INSTALADOR / "nodo.iss")
    assert "'abcdefghijklmnopqrstuvwxyz0123456789.:/-_'" in iss
    assert "matches!(c, '.' | ':' | '/' | '-' | '_')" in vinculo


def test_el_codigo_nunca_va_en_una_linea_de_comandos():
    vinculo = _rust("vinculo.rs")
    inicio_windows = vinculo.index("#[cfg(windows)]\npub mod plataforma")
    linux = vinculo[vinculo.index("#[cfg(not(windows))]\nmod plataforma"):inicio_windows]
    assert '.arg("--codigo-entrada")' in linux and '.arg("--codigo")' not in linux
    assert 'writeln!(entrada, "{codigo}")' in linux
    windows = vinculo[inicio_windows:]
    parametros = re.search(r"let parametros =\s*format!\(([^;]+)\);", windows).group(1)
    assert "codigo" not in parametros.replace("archivo-codigo", "")
    assert '"runas"' in windows and "--vincular-elevado" in parametros
    assert "create_new(true)" in windows and "remove_file(&archivo)" in windows
    assert '"-ArchivoCodigo"' in windows and "remove_file(archivo_codigo)" in windows


