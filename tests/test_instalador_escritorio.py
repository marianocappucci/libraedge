def test_la_accion_de_polkit_es_la_del_configurador():
    politica = ET.parse(LINUX / "ar.com.librasuite.libraedge-nodo.policy").getroot()
    accion = politica.find("action")
    assert accion.get("id") == "ar.com.librasuite.libraedge-nodo.vincular"
    ruta = {a.get("key"): a.text for a in accion.findall("annotate")}["org.freedesktop.policykit.exec.path"]
    assert re.search(r'pub const CONFIGURADOR: &str = "([^"]+)";', _rust("vinculo.rs")).group(1) == ruta
    assert ruta == "/opt/libraedge-nodo/instalador/instalar.sh"
    defaults = accion.find("defaults")
    assert defaults.find("allow_active").text == "auth_admin_keep"
    assert defaults.find("allow_any").text == "auth_admin"


