    assert "if ($ArchivoCodigo) { Remove-Item $ArchivoCodigo -Force" in canje
    # Ninguna variable del codigo se escribe en el transcript.
    assert not re.search(r"Write-(Host|Warning).*\$env:LIBRAEDGE_CODIGO", instalar)


