def test_instalar_ps1_sin_vincular_y_con_el_archivo_del_codigo():
    instalar = _texto(INSTALADOR / "instalar.ps1")
    sin = instalar[instalar.index("if ($SinVincular) {"):instalar.index("# Hasta crear o tocar la base")]
    assert "Crear-AccesosDelProducto -RaizNodo $RaizNodo -Plan $plan" in sin and "exit $salida" in sin
